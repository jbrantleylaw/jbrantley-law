const fmt = (val, fallback = '_________________________') => val || fallback;
const today = () => new Date().toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' });

function firmHeader() {
  return [
    new Paragraph({
      children: [new TextRun({ text: FIRM.name, bold: true, size: 32, color: '1B2A4A' })],
      alignment: AlignmentType.CENTER,
    }),
    new Paragraph({
      children: [new TextRun({ text: FIRM.attorney, size: 22, color: '1B2A4A' })],
      alignment: AlignmentType.CENTER,
    }),
    new Paragraph({
      children: [new TextRun({ text: `${FIRM.phone}  |  ${FIRM.email}  |  ${FIRM.website}`, size: 18, color: '666666' })],
      alignment: AlignmentType.CENTER,
    }),
    new Paragraph({
      children: [new TextRun({ text: '────────────────────────────────────────────', color: 'C9A84C' })],
      alignment: AlignmentType.CENTER,
    }),
    new Paragraph({ text: '' }),
  ];
}

function heading(text) {
  return new Paragraph({
    children: [new TextRun({ text, bold: true, size: 24, color: '1B2A4A' })],
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 240, after: 120 },
  });
}

function body(text, opts = {}) {
  return new Paragraph({
    children: [new TextRun({ text, size: 22, ...opts })],
    spacing: { after: 160 },
  });
}

function space() { return new Paragraph({ text: '', spacing: { after: 120 } }); }

function signatureLine(label) {
  return [
    new Paragraph({ children: [new TextRun({ text: '________________________________', size: 22 })], spacing: { before: 400, after: 80 } }),
    new Paragraph({ children: [new TextRun({ text: label, size: 20, color: '444444' })], spacing: { after: 240 } }),
  ];
}

function buildDoc(paragraphs) {
  return new Document({
    sections: [{
      properties: { page: { margin: { top: convertInchesToTwip(1.25), bottom: convertInchesToTwip(1.25), left: convertInchesToTwip(1.25), right: convertInchesToTwip(1.25) } } },
      children: paragraphs,
    }],
    styles: {
      paragraphStyles: [{
        id: 'Normal',
        name: 'Normal',
        run: { font: 'Georgia', size: 22 },
      }],
    },
  });
}

async function saveDoc(doc, filePath) {
  const buffer = await Packer.toBuffer(doc);
  fs.writeFileSync(filePath, buffer);
}

