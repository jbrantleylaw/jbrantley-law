async function generateDocument(templateKey, data, filePath) {
  const generators = {
    'engagement-letter': generateEngagementLetter,
    'non-engagement-letter': generateNonEngagementLetter,
    'intake-summary': generateIntakeSummaryDocx,
    'pi-demand-letter': generatePiDemandLetter,
    'pi-representation-letter': generatePiRepresentationLetter,
    'will-tx': generateWillTx,
    'will-ga': generateWillGa,
    'directive-tx': generateDirectiveTx,
    'directive-ga': generateDirectiveGa,
    'dpoa-tx': generateDpoaTx,
    'dpoa-ga': generateDpoaGa,
    'medical-poa-tx': generateMedicalPoaTx,
    'llc-operating-tx': generateLlcOperatingTx,
    'llc-operating-ga': generateLlcOperatingGa,
    'corporate-resolution-tx': generateCorporateResolutionTx,
    'annual-meeting-minutes': generateAnnualMeetingMinutes,
    'special-meeting-minutes': generateSpecialMeetingMinutes,
    'trademark-opinion': generateTrademarkOpinionMemo,
    'contract-review-memo': generateContractReviewMemo,
    'gov-engagement-letter': generateGovEngagementLetter,
  };
  const gen = generators[templateKey];
  if (!gen) throw new Error(`Unknown template: ${templateKey}`);
  await gen(data, filePath);
}

